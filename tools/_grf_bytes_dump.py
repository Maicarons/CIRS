import io, re
b=open("generated/cirs.grf","rb").read()
out=io.open("tools/_grf_bytes_dump.txt","w",encoding="utf-8")
def W(s=""): out.write(s+"\n")
def dump(pos,n=180):
    seg=b[max(0,pos-n//2):pos+n]
    W("  HEX: "+" ".join("%02X"%x for x in seg[:120]))
    try: W("  UTF8: "+repr(seg.decode("utf-8","replace")))
    except Exception as e: W("  ERR "+repr(e))
    W("  LAT1: "+repr(seg.decode("latin-1","replace")))
W("=== first Hangul (EA..ED) occurrence ===")
m=re.search(rb"[\xea-\xed][\x80-\xbf][\x80-\xbf]",b)
W("at %s"%m.start() if m else "NONE")
if m: dump(m.start())
W(""); W("=== first Cyrillic (D0/D1) occurrence ===")
m=re.search(rb"\xd0[\x80-\xbf]",b)
W("at %s"%m.start() if m else "NONE")
if m: dump(m.start())
W(""); W("=== first CJK E4..E9 occurrence ===")
m=re.search(rb"[\xe4-\xe9][\x80-\xbf][\x80-\xbf]",b)
W("at %s"%m.start() if m else "NONE")
if m: dump(m.start())
W(""); W("=== literal NML escape sequences in GRF ===")
for pat,name in [(rb"\\U[0-9A-Fa-f]{4}","\\UXXXX"),(rb"\\u[0-9A-Fa-f]{4}","\\uXXXX"),(rb"\\x[0-9A-Fa-f]{2}","\\xXX")]:
    W("  %-10s %d"%(name,len(re.findall(pat,b))))
    mm=re.search(pat,b)
    if mm: W("    first at %d: %r"%(mm.start(),mm.group()))
W(""); W("=== count of raw Hangul / Cyrillic / CJK 3-byte sequences ===")
W("  Hangul EA-ED: %d"%len(re.findall(rb"[\xea-\xed][\x80-\xbf][\x80-\xbf]",b)))
W("  Cyrillic D0-D1: %d"%len(re.findall(rb"[\xd0-\xd1][\x80-\xbf]",b)))
W("  CJK E4-E9: %d"%len(re.findall(rb"[\xe4-\xe9][\x80-\xbf][\x80-\xbf]",b)))
W("  Arabic D8-DB: %d"%len(re.findall(rb"[\xd8-\xdb][\x80-\xbf]",b)))
W("  Kana E3 81-83: %d"%len(re.findall(rb"\xe3[\x81-\x83][\x80-\xbf]",b)))
W(""); W("=== exact korean STR_GRF_NAME fragments ===")
for s in ["CIRS ","커뮤니티","산업 교체 세트","커뮤니티 산업","温和西部","CIRS 社区产业替换集"]:
    W("  %-24r %d"%(s,b.count(s.encode("utf-8"))))
out.close(); print("WROTE tools/_grf_bytes_dump.txt")
